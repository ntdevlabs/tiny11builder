def build_resw(items: dict[str, str]) -> str:
    root = ET.Element("root")
    for name in ("resmimetype", "version", "reader", "writer"):
        header = ET.SubElement(root, "resheader", {"name": name})
        value = ET.SubElement(header, "value")
        value.text = {
            "resmimetype": "text/microsoft-resx",
            "version": "2.0",
            "reader": "System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089",
            "writer": "System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089",
        }[name]
    for key in sorted(items):
        data = ET.SubElement(root, "data", {"name": key, "xml:space": "preserve"})
        ET.SubElement(data, "value").text = items[key]
    rough = ET.tostring(root, encoding="utf-8")
    pretty = minidom.parseString(rough).toprettyxml(indent="  ")
    # Drop the default XML declaration's standalone and keep a UTF-8 declaration.
    return '<?xml version="1.0" encoding="utf-8"?>\n' + "\n".join(pretty.splitlines()[1:])


